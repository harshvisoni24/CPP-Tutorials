#include<iostream>
using namespace std;
int main()
{
	int a=2,b=9;
	//Logical Operators in C++.
	cout<<"The value of a && b is : "<<(a&&b)<<endl;  //&& operator checks if both variable has same value or not.
	cout<<"The value of a || b is : "<<(a||b)<<endl;  //|| operator checks if any one of them has matching value or not.
	cout<<"The value of !a is : "<<(!a)<<endl;        //! operator will display value that is not assign to the operator.
	
	return 0;
}
