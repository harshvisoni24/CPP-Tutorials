/*What is Inheritance
1. Concept of Reusability in C++ is supported using it.
2. Existing Class is called as Base Class.
3. New class that is inherited is called Derived Class.
4. Reusing saves time and money.
5. There are different type of inheritance in C++.
--> Single Inheritance : Derived class with single base class.
--> Multiple Inheritance : More than one Base class.
--> Hierarchical Inheritance : More Derived class from single Base class.
--> Multilevel Inheritance : Deriving a class from already derived class.
--> Hybrid Inheritance : It is combination of Multilevel and Multiple Inheritance.
*/
